#!/usr/bin/env node
// Synthetic accounts in a fresh socket-only PostgreSQL; all finance functions are canonical SQL.
import assert from 'node:assert/strict';
import {loadCanonicalAdsFixture} from '../tests/ads-canonical-fixture.mjs';
import {mkdtempSync,readFileSync,existsSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {spawnSync,spawn} from 'node:child_process';
import {randomUUID} from 'node:crypto';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'../..');
const rr=resolve(root,'../RoadRunners/_codex/sql');
const scratch=mkdtempSync(resolve(tmpdir(),'ads-budget-increase-'));
const bin='/opt/homebrew/opt/postgresql@16/bin';
const env={PATH:process.env.PATH,LC_ALL:'C',TMPDIR:tmpdir()};
function run(name,args,input,fail=false){const r=spawnSync(resolve(bin,name),args,{input,encoding:'utf8',env,maxBuffer:24*1024*1024});if(r.status!==0&&!fail)throw Error(`${name}: ${r.error||''}${r.stdout}${r.stderr}`);return fail?r:r.stdout.trim();}
const args=['-X','-qAt','-v','ON_ERROR_STOP=1','-h',scratch,'-U','postgres','-d','postgres'];
const sql=(input,fail=false)=>run('psql',args,input,fail);
const read=name=>readFileSync(resolve(rr,name),'utf8');
const business=name=>readFileSync(resolve(root,'_codex/sql',name),'utf8');
let started=false;
try {
  run('initdb',['-D',resolve(scratch,'data'),'-U','postgres','-A','trust','--no-locale','-c','shared_memory_type=mmap','-c','dynamic_shared_memory_type=mmap']);
  run('pg_ctl',['-D',resolve(scratch,'data'),'-l',resolve(scratch,'postgres.log'),'-o',`-F -k ${scratch} -c listen_addresses=''`,'-w','start']);started=true;
  sql(`ALTER DATABASE postgres SET ads.paid_banner_test_fixture='isolated-local-v1'`);
  sql(`CREATE ROLE runner LOGIN; CREATE ROLE runner_dba LOGIN;
    CREATE TABLE public.tb_usuarios(id integer PRIMARY KEY,is_admin boolean DEFAULT false,is_dev boolean DEFAULT false);
    CREATE TABLE public.tb_contas(id_conta bigint PRIMARY KEY,status text NOT NULL);
    CREATE TABLE public.tb_evento_corridas(id_evento integer PRIMARY KEY,ativo boolean NOT NULL,estado text);
    CREATE TABLE public.tb_conta_usuarios(id_conta bigint,id_usuario integer,status text,papel text);
    CREATE TABLE public.tb_conta_eventos(id_conta bigint,id_evento integer,status text,PRIMARY KEY(id_conta,id_evento));
    CREATE TABLE public.tb_conta_cadastro_solicitacoes(id_solicitacao bigint,id_conta bigint,id_usuario integer,status text);
    CREATE TABLE public.tb_conta_evento_solicitacoes(id_conta bigint,id_evento integer,id_usuario_solicitante integer,status text);`);
  await loadCanonicalAdsFixture(sql,root);
  sql(`    INSERT INTO public.tb_usuarios VALUES(901,true,false),(902,false,false),(903,false,false),(904,false,false);
    INSERT INTO public.tb_contas VALUES(1,'ATIVA'),(2,'ATIVA'),(3,'PENDENTE');
    INSERT INTO public.tb_conta_usuarios VALUES(2,902,'ATIVO','OWNER'),(2,903,'ATIVO','VISUALIZADOR'),(3,904,'ATIVO','OWNER');
    INSERT INTO public.tb_evento_corridas VALUES(901,true,'SC'); INSERT INTO public.tb_conta_eventos VALUES(2,901,'ATIVO');`);
  sql(read('2026-09-16_ads_paid_banners.sql'));
  // Install the existing real delegation authorization helper as in production.
  sql(`ALTER TABLE public.tb_conta_usuarios ADD COLUMN id_conta_usuario bigserial PRIMARY KEY;
      CREATE TABLE public.tb_business_permissoes(id_permissao bigserial PRIMARY KEY,codigo varchar(100) UNIQUE NOT NULL,descricao varchar(255) NOT NULL,ativo boolean NOT NULL DEFAULT true);`);
  sql(business('2026-10-03_business_account_delegation.sql'));
  sql('GRANT SELECT ON ALL TABLES IN SCHEMA public TO ads_owner');
  sql(business('2026-10-03_business_account_delegation_ads.sql'));
  const migration=business('2026-10-24_ads_increase_campaign_budget.sql');
  sql(migration);
  const fails=(q,pattern)=>{const r=sql(q,true);assert.notEqual(r.status,0);assert.match(r.stderr,pattern);};
  sql(`SELECT ads.credit_account(2,1000,'budget-fixture-credit','MANUAL',901,'{}')`);
  const c=JSON.parse(sql(`SELECT row_to_json(x) FROM ads.save_event_campaign(NULL,2,901,'rr-home-upcoming-native','Synthetic budget','https://example.test/event',0.94,100,NULL,now(),now()+interval '10 days','ALL','BR',NULL,902) x`));
  const id=c.campaign_id;
  const request=sql(`SELECT campaign_review_request_id FROM ads.submit_campaign_review('${id}',2,902,901)`);
  const increase=(expected,next,actor=902,account=2)=>`SELECT ads.increase_campaign_budget('${id}',${account},${actor},${expected},${next})`;
  fails(increase(100,200),/ADS_BUDGET_NOT_APPROVED/);
  sql(`SELECT * FROM ads.review_campaign('${id}','APPROVE',901,'Approved synthetic fixture','budget-fixture-approval',${request})`);
  const initial=sql(`SELECT row_to_json(x) FROM (SELECT status,(SELECT status FROM ads.campaign_review_requests WHERE campaign_review_request_id=${request}) AS review FROM ads.campaigns WHERE campaign_id='${id}') x`);
  assert.equal(JSON.parse(initial).status,'ACTIVE');
  sql(increase(100,200));
  assert.equal(sql(`SELECT row_to_json(x) FROM (SELECT status,(SELECT status FROM ads.campaign_review_requests WHERE campaign_review_request_id=${request}) AS review FROM ads.campaigns WHERE campaign_id='${id}') x`),initial);
  assert.equal(sql(`SELECT previous_budget||':'||new_budget FROM ads.campaign_budget_history WHERE campaign_id='${id}'`),'100.00:200.00');
  assert.equal(sql(`SELECT available_balance FROM ads.account_balances WHERE account_id=2`),'1000.00');
  console.log('PASS approved ACTIVE increase preserves review/status/wallet and writes old/new budget audit');
  for(const next of [200,199]) fails(increase(200,next),/ADS_BUDGET_INCREASE_ONLY/);
  for(const next of ['NULL',-1,0,'201.001',"'NaN'","'Infinity'",'1000000000000']) fails(increase(200,next),/ADS_BUDGET_INVALID/);
  fails(increase(100,300),/ADS_BUDGET_STALE/);
  for(const actor of [903,904])fails(increase(200,300,actor),/ADS_BUDGET_FORBIDDEN/);
  fails(increase(200,300,901,1),/ADS_BUDGET_NOT_FOUND/);
  fails(`BEGIN; SELECT set_config('business.delegation_context','{}',true); ${increase(200,300,901)}; COMMIT;`,/ADS_BUDGET_FORBIDDEN|context|deleg/i);
  console.log('PASS decrease/equal/invalid/stale/foreign/viewer/delegated admin escalation denied');
  fails(`UPDATE ads.campaigns SET budget_total=300,name='Changed creative' WHERE campaign_id='${id}'`,/nova revisao/);
  fails(`UPDATE ads.campaigns SET budget_total=300,cpc_bid=1.32 WHERE campaign_id='${id}'`,/nova revisao/);
  fails(`UPDATE ads.campaigns SET budget_total=300,target_region_code='SP' WHERE campaign_id='${id}'`,/nova revisao/);
  assert.equal(sql(`SELECT budget_total FROM ads.campaigns WHERE campaign_id='${id}'`),'200.00');
  sql(`SELECT ads.change_campaign_status('${id}','PAUSED',902,'Synthetic pause')`);
  sql(increase(200,250));
  assert.equal(sql(`SELECT status FROM ads.campaigns WHERE campaign_id='${id}'`),'PAUSED');
  assert.equal(sql(`SELECT status FROM ads.campaign_review_requests WHERE campaign_review_request_id=${request}`),'APPROVED');
  console.log('PASS pure increase does not admit creative/CPC/targeting changes; PAUSED remains PAUSED');
  sql(`CREATE FUNCTION public.fail_budget_audit() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'synthetic audit failure'; END; $$;
       CREATE TRIGGER fail_budget_audit BEFORE INSERT ON ads.campaign_budget_history FOR EACH ROW EXECUTE FUNCTION public.fail_budget_audit()`);
  fails(increase(250,300),/synthetic audit failure/);
  assert.equal(sql(`SELECT budget_total FROM ads.campaigns WHERE campaign_id='${id}'`),'250.00');
  sql('DROP TRIGGER fail_budget_audit ON ads.campaign_budget_history');
  sql(`SELECT ads.change_campaign_status('${id}','ENDED',902,'Synthetic end')`);
  fails(increase(250,300),/ADS_BUDGET_NOT_APPROVED/);
  fails(migration,/baseline drift/);
  console.log('PASS audit failure rolls back budget; ended rejected; migration reapply refuses drift');
}catch(error){console.error(error.message);process.exitCode=1;}
finally{if(started)run('pg_ctl',['-D',resolve(scratch,'data'),'-m','fast','-w','stop']);console.log(`Isolated fixture retained: ${scratch}`);}
