#!/usr/bin/env python3
"""Build two local consumer packages: exact approved-pair compatibility, then new only.

No remote access, DB execution or publication. Reuses the audited cutover inputs
and the canonical press renderer. Only the small explicit SQL/JS patch below adds
compatibility; no metric, access or fallback policy is changed.
"""
import argparse
import difflib
import importlib.util
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile

HERE=Path(__file__).resolve().parent
spec=importlib.util.spec_from_file_location('consumer_cutover_compatible',HERE.parent/'consumer-cutover/consumer_cutover.py')
cutover=importlib.util.module_from_spec(spec);spec.loader.exec_module(cutover)


def cfc_replacements(db,ids):
    old_pub=db['publication_id'];old_run=db['public_run'];old_rev=db['public_revision']
    pub=ids['publication_id'];run=ids['public_run'];rev=ids['public_revision']
    return [
        ('                a.payload AS publication\n', '                a.publicacao_id,a.payload AS publication\n'),
        (f'AND a.publicacao_id={old_pub} AND jsonb_extract_path_text',f'AND a.publicacao_id IN ({old_pub},{pub}) AND jsonb_extract_path_text'),
        (f"""            SELECT jsonb_extract_path(result,'rows','0','payload','release') AS narrative
            FROM estudo.notebook_runs
            WHERE id={old_run} AND cell_id=420 AND cell_version={old_rev} AND frozen AND status='ok' AND NOT truncated AND row_count=1""",
         f"""            SELECT approved_pairs.publication_id,r.id AS narrative_run,r.cell_version AS narrative_revision,
                jsonb_extract_path(r.result,'rows','0','payload','release') AS narrative
            FROM (VALUES ({old_pub}::bigint,{old_run}::bigint,{old_rev}::integer),
                         ({pub}::bigint,{run}::bigint,{rev}::integer)) approved_pairs(publication_id,run_id,revision)
            JOIN estudo.notebook_runs r ON r.id=approved_pairs.run_id AND r.cell_id=420 AND r.cell_version=approved_pairs.revision
            WHERE r.frozen AND r.status='ok' AND NOT r.truncated AND r.row_count=1"""),
        ('            SELECT p.*\n            FROM paired_source p CROSS JOIN paired_public n',
         '            SELECT p.*,n.narrative_run,n.narrative_revision\n            FROM paired_source p JOIN paired_public n ON n.publication_id=p.publicacao_id'),
        (f"'narrativa',jsonb_build_object('celula',420,'execucao',{old_run},'revisao',{old_rev})",
         "'narrativa',jsonb_build_object('celula',420,'execucao',narrative_run,'revisao',narrative_revision)")]


def compatible_cfc(source,db,ids):
    result=source
    for old,new in cfc_replacements(db,ids):result=cutover.exact(result,old,new)
    restored=result
    for old,new in reversed(cfc_replacements(db,ids)):restored=cutover.exact(restored,new,old)
    if restored!=source:raise ValueError('Unexpected non-pin CFC change')
    return result


def compatible_js(source,old_run,new_run):
    old_run=cutover.positive(old_run,'old_public_run');new_run=cutover.positive(new_run,'new_public_run')
    if old_run==new_run:raise ValueError('Compatibility requires two distinct approved runs')
    return cutover.exact(source,f'meta.narrativa?.execucao!=={old_run}',f'![{old_run},{new_run}].includes(meta.narrativa?.execucao)')


def press_files(source,overlay,business,rr):
    spec=importlib.util.spec_from_file_location('compatible_press_renderer',cutover.reader_path(rr))
    reader=importlib.util.module_from_spec(spec);spec.loader.exec_module(reader)
    reader.ROOT=rr;reader.BUSINESS=business
    def validated(path):
        path=Path(path).resolve()
        key=('business/'+str(path.relative_to(business))) if path.is_relative_to(business) else ('portal/'+str(path.relative_to(rr)))
        if key not in source:raise ValueError('Canonical generator read outside validated baseline: '+key)
        content=overlay.get(key,source[key]);reader.SOURCES[key]=cutover.sha(content.encode());return content
    reader.source=validated
    html25=reader.principal_html(2025);html26=reader.principal_html(2026)
    projection=reader.extract_projection(validated(business/'estudos/includes/StudyAccess.cfc'))
    index=source['portal/'+cutover.PRESS+'index.cfm']
    start=index.index("<cfif VARIABLES.pressYear EQ '2025'>")
    wrapper=index[index.index('<cfprocessingdirective'):start]
    index=wrapper+"<cfif VARIABLES.pressYear EQ '2025'>"+html25+'<cfelse>'+html26+'</cfif>\n'
    css=validated(business/'estudos/leitor/estudo.css')
    css=re.sub(r"url\((\s*[\"']?)assets/",lambda m:'url('+m[1]+reader.RR_ASSETS+'assets/',css)
    js=reader.partial_script()
    stamp='<!--- Generated by reader-builder.py. Canonical sources SHA-256: '+json.dumps(reader.SOURCES,ensure_ascii=False,sort_keys=True,separators=(',',':'))+' --->\n'
    return {'portal/'+cutover.PRESS+'index.cfm':stamp+index,
            'portal/'+cutover.PRESS+'dados.cfm':stamp+reader.principal_data(projection),
            'portal/'+cutover.PRESS+'parcial-2026.js':'// Generated from Business/estudos/leitor/parcial.js; rebuild via reader-builder.py.\n'+js,
            'portal/'+cutover.PRESS+'estudo-2026.css':'/* Generated from Business/estudos/leitor/estudo.css; rebuild via reader-builder.py. */\n'+css},reader.SOURCES


def build(baseline,ids,evidence,output,business=cutover.BUSINESS,rr=cutover.RR):
    ids,db,source=cutover.validate_inputs(baseline,ids,evidence,business,rr)
    business=Path(business).resolve();rr=Path(rr).resolve();output=Path(output).resolve()
    if output.exists():raise ValueError('Use a fresh isolated output directory')
    if output in [business,rr] or output.is_relative_to(business/'estudos') or output.is_relative_to(business/'estudo') or output.is_relative_to(rr/'brasilquecorreprovas'):
        raise ValueError('Output cannot be runtime')
    cfc=compatible_cfc(source['business/estudos/includes/StudyAccess.cfc'],db,ids)
    js=compatible_js(source['business/estudos/leitor/parcial.js'],db['public_run'],ids['public_run'])
    version=f"consumer-compatible-{db['publication_id']}-{ids['publication_id']}-{ids['public_run']}"
    overlay={'business/estudos/includes/StudyAccess.cfc':cfc,'business/estudos/leitor/parcial.js':js,
             'business/estudos/leitor/index.cfm':cutover.exact(source['business/estudos/leitor/index.cfm'],'?v=q3-20261109-comparativo','?v='+version),
             'business/estudo/anual/index.cfm':cutover.exact(source['business/estudo/anual/index.cfm'],'?v=edicoes-20261010-1','?v='+version)}
    press,hashes=press_files(source,overlay,business,rr);overlay.update(press)
    pairs=[{'publication_id':db['publication_id'],'public_run':db['public_run'],'revision':db['public_revision']},
           {'publication_id':ids['publication_id'],'public_run':ids['public_run'],'revision':ids['public_revision']}]
    output.parent.mkdir(parents=True,exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='consumer-compatible-build-',dir=output.parent) as tmp:
        work=Path(tmp)
        final=cutover.build(baseline,ids,evidence,work/'final-only',business,rr)
        compat=work/'compatible';shutil.copytree(work/'final-only/candidate',compat/'candidate')
        patch=[];manifest={}
        node=shutil.which('node')
        for key,content in overlay.items():
            dest=compat/'candidate'/key;dest.write_bytes(content.encode())
            manifest[key]={'before_sha256':cutover.sha(source[key].encode()),'candidate_sha256':cutover.sha(content.encode())}
            patch.extend(difflib.unified_diff(source[key].splitlines(True),content.splitlines(True),fromfile='a/'+key,tofile='b/'+key))
            if dest.suffix=='.js':subprocess.run([node,'--check',str(dest)],capture_output=True,text=True,check=True,timeout=30)
        subprocess.run([node,str(rr/'_codex/scripts/check_rr_teams_release_hold.mjs'),'--root',str(compat/'candidate/portal')],capture_output=True,text=True,check=True,timeout=60)
        compat_report={**final,'mode':'two-approved-pairs-before-DataGrip','approved_pairs':pairs,
                       'runtime_files':manifest,'source_hashes':hashes,
                       'baseline_origin':'actual production/local snapshot before compatible release',
                       'teams_hold':{'checkout':True,'candidate':True},
                       'changes':'Two publication/narrative pairs joined by publication ID; exact frozen revisions. Existing metrics/auth/fallback preserved.'}
        (compat/'manifest.json').write_text(json.dumps(compat_report,ensure_ascii=False,indent=2)+'\n')
        (compat/'runtime.patch').write_text(''.join(patch))
        (compat/'patch-plan.json').write_text(json.dumps({'approved_pairs':pairs,'cfc_exact_replacements':[{'before':a,'after':b} for a,b in cfc_replacements(db,ids)]},ensure_ascii=False,indent=2)+'\n')
        # After DataGrip, removal must compare against the compatible bytes actually deployed,
        # not the pre-transition bytes from the original production snapshot.
        final_patch=[]
        for key,record in final['runtime_files'].items():
            record['before_sha256']=manifest[key]['candidate_sha256']
            content=(work/'final-only/candidate'/key).read_text()
            final_patch.extend(difflib.unified_diff(overlay[key].splitlines(True),content.splitlines(True),fromfile='a/'+key,tofile='b/'+key))
        final.update({'mode':'new-approved-pair-after-DataGrip',
                      'baseline_origin':'expected compatible release; recapture/confirm these production hashes after DataGrip before transfer',
                      'approved_pairs':[pairs[1]]})
        (work/'final-only/manifest.json').write_text(json.dumps(final,ensure_ascii=False,indent=2)+'\n')
        (work/'final-only/runtime.patch').write_text(''.join(final_patch))
        report={'ids':ids,'approved_pairs':pairs,'baseline_capture':baseline['captured_at'],
                'compatible_manifest':'compatible/manifest.json','final_manifest':'final-only/manifest.json',
                'database_review_artifact':'final-only/database-cutover-DBA.sql',
                'teams_hold':{'compatible':True,'final_only':True},'runtime_publication':False,'database_execution':False}
        (work/'build-report.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')
        os.replace(work,output)
    return report


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    for name in ['baseline','ids','evidence','output-dir']:parser.add_argument('--'+name,type=Path,required=True)
    a=parser.parse_args()
    print(json.dumps(build(json.loads(a.baseline.read_text()),json.loads(a.ids.read_text()),json.loads(a.evidence.read_text()),a.output_dir),ensure_ascii=False,indent=2))


if __name__=='__main__':main()
