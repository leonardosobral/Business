CREATE FUNCTION estudo.notebook_cell_version() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog AS $fn$
BEGIN
 IF TG_OP='INSERT' THEN NEW.version:=1;
 ELSE NEW.version:=OLD.version+1; END IF;
 NEW.updated_at:=clock_timestamp();
 RETURN NEW;
END;
$fn$;
CREATE FUNCTION estudo.notebook_cell_revision() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog AS $fn$
BEGIN
 INSERT INTO estudo.notebook_revisions
 VALUES(NEW.id,NEW.version,NEW.notebook_id,NEW.cell_type,NEW.lang,NEW.content,NEW.archived,NEW.origem,NEW.updated_at,NEW.updated_by,encode(sha256(convert_to(NEW.content,'UTF8')),'hex'));
 RETURN NEW;
END;
$fn$;
