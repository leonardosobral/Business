CREATE TABLE estudo.notebook_runs (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 cell_id bigint NOT NULL,cell_version integer NOT NULL,
 sql_text text NOT NULL,sql_sha256 text NOT NULL CHECK(sql_sha256 ~ '^[a-f0-9]{64}$'),
 executed_by bigint NOT NULL,started_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 finished_at timestamptz,duration_ms integer CHECK(duration_ms>=0),
 status text NOT NULL CHECK(status IN ('running','ok','error')),
 result jsonb,row_count integer NOT NULL DEFAULT 0 CHECK(row_count>=0),
 truncated boolean NOT NULL DEFAULT false,error_message text NOT NULL DEFAULT '',
 frozen boolean NOT NULL DEFAULT false,frozen_at timestamptz,frozen_by bigint,
 title text NOT NULL DEFAULT '',note text NOT NULL DEFAULT '',
 FOREIGN KEY(cell_id,cell_version) REFERENCES estudo.notebook_revisions(cell_id,version),
 CHECK(result IS NULL OR (jsonb_typeof(result)='object' AND jsonb_typeof(result->'columns')='array' AND jsonb_typeof(result->'rows')='array')),
 CHECK(status<>'ok' OR (result IS NOT NULL AND row_count=jsonb_array_length(result->'rows'))),
 CHECK(NOT frozen OR (status='ok' AND NOT truncated AND length(btrim(title)) BETWEEN 1 AND 200))
);
CREATE INDEX notebook_runs_cell_time ON estudo.notebook_runs(cell_id,id DESC);
CREATE FUNCTION estudo.notebook_run_protect() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog AS $fn$
BEGIN
 IF TG_OP IN ('DELETE','TRUNCATE') THEN RAISE EXCEPTION 'Execucao imutavel'; END IF;
 IF TG_OP='INSERT' THEN
   IF NEW.frozen THEN RAISE EXCEPTION 'Congele somente uma execucao salva completa'; END IF;
   RETURN NEW;
 END IF;
 IF OLD.frozen THEN RAISE EXCEPTION 'Resultado congelado imutavel'; END IF;
 IF OLD.status='running' AND NEW.status IN ('ok','error') AND NOT NEW.frozen THEN
   IF NEW.cell_id<>OLD.cell_id OR NEW.cell_version<>OLD.cell_version OR NEW.sql_text<>OLD.sql_text OR NEW.sql_sha256<>OLD.sql_sha256 OR NEW.executed_by<>OLD.executed_by OR NEW.started_at<>OLD.started_at THEN
     RAISE EXCEPTION 'Identidade da execucao imutavel';
   END IF;
   RETURN NEW;
 END IF;
 IF OLD.status='ok' AND NEW.frozen AND NOT OLD.truncated
   AND (to_jsonb(NEW)-ARRAY['frozen','frozen_at','frozen_by','title','note'])=(to_jsonb(OLD)-ARRAY['frozen','frozen_at','frozen_by','title','note'])
 THEN
   IF length(btrim(NEW.title)) NOT BETWEEN 1 AND 200 THEN RAISE EXCEPTION 'Titulo do congelamento obrigatorio'; END IF;
   NEW.frozen_at:=clock_timestamp();
   RETURN NEW;
 END IF;
 RAISE EXCEPTION 'Execucao imutavel; congelamento exige resultado completo';
END;
$fn$;
CREATE TRIGGER notebook_run_protect BEFORE INSERT OR UPDATE OR DELETE ON estudo.notebook_runs FOR EACH ROW EXECUTE FUNCTION estudo.notebook_run_protect();
CREATE TRIGGER notebook_run_no_truncate BEFORE TRUNCATE ON estudo.notebook_runs FOR EACH STATEMENT EXECUTE FUNCTION estudo.notebook_run_protect();

