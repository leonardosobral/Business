-- Moves the existing notebook tables. Does not modify estudo.snapshots.
SET LOCAL lock_timeout='3s';
SET LOCAL statement_timeout='30s';
SELECT pg_advisory_xact_lock(9282026,1);
DO $preflight$
BEGIN
 IF to_regnamespace('estudo') IS NULL THEN RAISE EXCEPTION 'Schema estudo ausente'; END IF;
 IF to_regclass('public.notebooks') IS NULL OR to_regclass('public.notebook_cells') IS NULL THEN
   RAISE EXCEPTION 'Acervo de origem ausente ou migracao ja aplicada; conferir recibo antes de repetir';
 END IF;
 IF to_regclass('estudo.notebooks') IS NOT NULL OR to_regclass('estudo.notebook_cells') IS NOT NULL THEN
   RAISE EXCEPTION 'Destino ja existe; migracao interrompida';
 END IF;
 IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname='estudo_reader') THEN
   RAISE EXCEPTION 'Papel estudo_reader ja existe; revisar antes da migracao';
 END IF;
END;
$preflight$;
LOCK TABLE public.notebooks,public.notebook_cells IN ACCESS EXCLUSIVE MODE;
DO $validate$
BEGIN
 IF EXISTS(SELECT notebook_id FROM public.notebooks GROUP BY notebook_id HAVING count(*)>1)
 OR EXISTS(SELECT 1 FROM public.notebooks WHERE notebook_title IS NULL)
 OR EXISTS(SELECT 1 FROM public.notebook_cells c LEFT JOIN public.notebooks n USING(notebook_id) WHERE n.notebook_id IS NULL)
 THEN RAISE EXCEPTION 'Acervo legado inconsistente; corrigir antes de migrar'; END IF;
END;
$validate$;
