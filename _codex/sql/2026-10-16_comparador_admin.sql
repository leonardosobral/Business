BEGIN;
CREATE TABLE IF NOT EXISTS comparador.tb_produto_editorial (
 id_produto integer PRIMARY KEY REFERENCES comparador.tb_produto(id_produto) ON DELETE RESTRICT,
 estado varchar(16) NOT NULL CHECK (estado IN ('rascunho','publicado','arquivado')),
 revisao bigint NOT NULL DEFAULT 1 CHECK (revisao > 0),
 atualizado_em timestamptz NOT NULL DEFAULT clock_timestamp(),
 ator_id bigint NOT NULL CHECK (ator_id > 0)
);
CREATE TABLE IF NOT EXISTS comparador.tb_admin_auditoria (
 id_auditoria bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_produto integer NOT NULL REFERENCES comparador.tb_produto(id_produto) ON DELETE RESTRICT,
 ator_id bigint NOT NULL CHECK (ator_id > 0),
 acao varchar(32) NOT NULL,
 registrado_em timestamptz NOT NULL DEFAULT clock_timestamp(),
 antes jsonb,
 depois jsonb NOT NULL
);
CREATE INDEX IF NOT EXISTS tb_admin_auditoria_produto_idx ON comparador.tb_admin_auditoria(id_produto,id_auditoria DESC);
CREATE OR REPLACE VIEW comparador.vw_produto_publico AS
 SELECT p.* FROM comparador.tb_produto p
 WHERE NOT EXISTS (SELECT 1 FROM comparador.tb_produto_editorial e WHERE e.id_produto=p.id_produto AND e.estado<>'publicado');
COMMENT ON TABLE comparador.tb_produto_editorial IS 'Ausência de linha significa publicado legado. Novos produtos Business são rascunhos até publicação explícita.';
COMMENT ON VIEW comparador.vw_produto_publico IS 'Contrato público do catálogo: exclui rascunhos e arquivados; preserva legado sem estado.';
COMMIT;
