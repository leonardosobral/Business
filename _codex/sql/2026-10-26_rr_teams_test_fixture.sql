-- Teams — fixture isolada para testes de integração; não contém Teams reais.
-- Execute apenas para habilitar a suíte nativa antes da publicação.
-- As linhas de teste serão criadas em transação e integralmente revertidas.
-- Executar em cliente PostgreSQL conectado ao banco RR como runner_dba.
-- Apenas objetos novos de Teams; não altera usuários, eventos, credenciais ou grants existentes.
-- Em caso de erro, a transação inteira é revertida. Não executar trechos isoladamente.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';
DO $teams_owner$
BEGIN
 IF current_user <> 'runner_dba' THEN
  RAISE EXCEPTION 'Execute este DDL autenticado como runner_dba; nenhuma credencial ou permissão será alterada pelo script.';
 END IF;
END
$teams_owner$;

-- Additive Teams domain. No changes to existing tables, grants or credentials.
CREATE SCHEMA IF NOT EXISTS rr_teams_test AUTHORIZATION runner_dba;
CREATE TABLE IF NOT EXISTS rr_teams_test.team (
 id_team bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 slug varchar(200) UNIQUE,
 name varchar(160) NOT NULL,
 type varchar(20) NOT NULL CHECK(type IN ('TREINADOR','ASSESSORIA','CLUBE','ACADEMIA','GRUPO','EMPRESA')),
 document varchar(14) NOT NULL CHECK(document ~ '^([0-9]{11}|[0-9]{14})$'),
 owner_name varchar(200) NOT NULL,
 technical_name varchar(200) NOT NULL,
 cref varchar(30) NOT NULL,
 cref_uf char(2) NOT NULL,
 email varchar(255) NOT NULL,
 phone varchar(20) NOT NULL,
 whatsapp varchar(20) NOT NULL,
 city varchar(100) NOT NULL,
 uf char(2) NOT NULL,
 attendance varchar(15) NOT NULL CHECK(attendance IN ('PRESENCIAL','ONLINE','AMBOS')),
 description varchar(1600) NOT NULL DEFAULT '',
 website varchar(500) NOT NULL DEFAULT '',
 status varchar(15) NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','ACTIVE','CHANGES','REJECTED','SUSPENDED','ARCHIVED')),
 requested_by integer NOT NULL REFERENCES public.tb_usuarios(id),
 reviewed_by integer REFERENCES public.tb_usuarios(id),
 reviewed_at timestamptz,
 review_note varchar(1600) NOT NULL DEFAULT '',
 cref_evidence varchar(1600) NOT NULL DEFAULT '',
 cref_verified_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 version integer NOT NULL DEFAULT 1
);
CREATE UNIQUE INDEX IF NOT EXISTS team_document_name ON rr_teams_test.team(document,lower(name));
CREATE INDEX IF NOT EXISTS team_directory ON rr_teams_test.team(status,uf,city,id_team);
CREATE TABLE IF NOT EXISTS rr_teams_test.admin (
 team_id bigint NOT NULL REFERENCES rr_teams_test.team(id_team),
 user_id integer NOT NULL REFERENCES public.tb_usuarios(id),
 role varchar(10) NOT NULL CHECK(role IN ('OWNER','ADMIN','VIEWER')),
 accepted_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(team_id,user_id)
);
CREATE INDEX IF NOT EXISTS team_admin_user ON rr_teams_test.admin(user_id,team_id);
CREATE TABLE IF NOT EXISTS rr_teams_test.athlete_clock (
 user_id integer PRIMARY KEY REFERENCES public.tb_usuarios(id),
 next_change_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS rr_teams_test.membership (
 id_membership bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 team_id bigint NOT NULL REFERENCES rr_teams_test.team(id_team),
 user_id integer NOT NULL REFERENCES public.tb_usuarios(id),
 started_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 ended_at timestamptz,
 end_reason varchar(30),
 ended_by integer REFERENCES public.tb_usuarios(id),
 consent_version varchar(30) NOT NULL DEFAULT 'teams-sports-v1',
 CHECK(ended_at IS NULL OR ended_at>=started_at)
);
CREATE UNIQUE INDEX IF NOT EXISTS one_active_team_per_athlete ON rr_teams_test.membership(user_id) WHERE ended_at IS NULL;
CREATE INDEX IF NOT EXISTS team_membership_page ON rr_teams_test.membership(team_id,ended_at,id_membership);
CREATE INDEX IF NOT EXISTS athlete_membership_history ON rr_teams_test.membership(user_id,id_membership DESC);
CREATE TABLE IF NOT EXISTS rr_teams_test.exclusion (
 team_id bigint NOT NULL REFERENCES rr_teams_test.team(id_team),
 user_id integer NOT NULL REFERENCES public.tb_usuarios(id),
 removed_by integer NOT NULL REFERENCES public.tb_usuarios(id),
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(team_id,user_id)
);
CREATE TABLE IF NOT EXISTS rr_teams_test.admin_invite (
 id_invite bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 team_id bigint NOT NULL REFERENCES rr_teams_test.team(id_team),
 email varchar(255) NOT NULL,
 role varchar(10) NOT NULL CHECK(role IN ('ADMIN','VIEWER')),
 token_hash char(64) NOT NULL UNIQUE,
 created_by integer NOT NULL REFERENCES public.tb_usuarios(id),
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 expires_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP+interval '7 days',
 accepted_by integer REFERENCES public.tb_usuarios(id),
 accepted_at timestamptz,
 revoked_at timestamptz
);
CREATE INDEX IF NOT EXISTS team_invites ON rr_teams_test.admin_invite(team_id,created_at DESC);
CREATE TABLE IF NOT EXISTS rr_teams_test.recruit_invite (
 id_invite bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 requested_by integer NOT NULL REFERENCES public.tb_usuarios(id),
 team_name varchar(160) NOT NULL,
 channel varchar(10) NOT NULL CHECK(channel IN ('EMAIL','WHATSAPP')),
 destination varchar(255) NOT NULL,
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 approved_team_id bigint REFERENCES rr_teams_test.team(id_team)
);
CREATE INDEX IF NOT EXISTS recruit_rate ON rr_teams_test.recruit_invite(requested_by,created_at DESC);
CREATE TABLE IF NOT EXISTS rr_teams_test.audit (
 id_audit bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 team_id bigint REFERENCES rr_teams_test.team(id_team),
 actor_id integer REFERENCES public.tb_usuarios(id),
 subject_id integer REFERENCES public.tb_usuarios(id),
 event varchar(50) NOT NULL,
 detail varchar(1600) NOT NULL DEFAULT '',
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS team_audit_page ON rr_teams_test.audit(team_id,id_audit DESC);
CREATE TABLE IF NOT EXISTS rr_teams_test.funnel (
 id_event bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id integer NOT NULL REFERENCES public.tb_usuarios(id),
 team_id bigint REFERENCES rr_teams_test.team(id_team),
 event varchar(30) NOT NULL CHECK(event IN ('JOIN','LEAVE','REMOVED','INVITE','ADMIN_ACCEPT','RETURN')),
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS team_funnel ON rr_teams_test.funnel(team_id,created_at,event);
CREATE TABLE IF NOT EXISTS rr_teams_test.notice (
 id_notice bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id integer NOT NULL REFERENCES public.tb_usuarios(id),
 message varchar(500) NOT NULL,
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 read_at timestamptz
);
CREATE TABLE IF NOT EXISTS rr_teams_test.mail_outbox (
 id_mail bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 destination varchar(255) NOT NULL,
 recipient_name varchar(200) NOT NULL DEFAULT '',
 subject varchar(200) NOT NULL,
 body text NOT NULL,
 status varchar(10) NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','SENDING','SENT','FAILED')),
 attempts integer NOT NULL DEFAULT 0,
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 next_attempt_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 sent_at timestamptz,
 claimed_at timestamptz
);
CREATE INDEX IF NOT EXISTS teams_mail_pending ON rr_teams_test.mail_outbox(status,next_attempt_at,id_mail);

CREATE TABLE IF NOT EXISTS rr_teams_test.schema_version (
 version integer PRIMARY KEY,
 installed_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
INSERT INTO rr_teams_test.schema_version(version) VALUES(1) ON CONFLICT(version) DO NOTHING;

COMMIT;
